  yamlLines.push(`  currency: "${obl.financial_obligation.currency}"`);

  yamlLines.push('downstream_projections:');
  yamlLines.push(`  commercial_shopping_ref: ${obl.downstream_projections.commercial_shopping_ref ? `"${obl.downstream_projections.commercial_shopping_ref}"` : 'null'}`);
